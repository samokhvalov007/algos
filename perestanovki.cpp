#include <iostream>

constexpr int NMAX = 100;              // максимальный размер множества (размер массивов)

// ---------- Каркас backtrack (из листинга 9.3, но универсальный) ----------

void backtrack(int a[], int k, int n); // предварительное объявление (определение ниже)

// ---------- Листинг 9.5: construct_candidates для перестановок ----------

// Заполняет c[] числами, которые можно поставить на позицию k
void construct_candidates(int a[], int k, int n, int c[], int *nc) {
    int i;                             // счётчик для циклов
    bool in_perm[NMAX];                // флаги: какие числа уже заняты в a[1..k-1]

    // 1. Сброс: пока ни одно число не помечено как занятое
    for (i = 1; i < NMAX; i++) {
        in_perm[i] = false;            // все ячейки — свободны
    }

    // 2. Отметить те числа, что уже стоят в a[1..k-1]
    for (i = 1; i < k; i++) {          // идём по уже заполненным позициям
        in_perm[a[i]] = true;          // число a[i] занято — помечаем
    }

    // 3. Собрать всех свободных в c[] — это и есть кандидаты
    *nc = 0;                           // пока кандидатов ноль (пишем по указателю)
    for (i = 1; i <= n; i++) {         // проходим по всем числам от 1 до n
        if (!in_perm[i]) {             // если число i ещё не занято...
            c[*nc] = i;                // ...записываем его в массив кандидатов
            (*nc)++;                   // увеличиваем счётчик кандидатов
        }
    }
}

// ---------- Листинг 9.6: остальные процедуры для перестановок ----------

// Печатает готовую перестановку: a[1], a[2], ..., a[k]
void process_solution(int a[], int k, int n) {
    for (int i = 1; i <= k; i++) {     // проходим по всем позициям (нумерация с 1)
        std::cout << " " << a[i];      // печатаем число, стоящее на позиции i
    }
    std::cout << "\n";                 // перевод строки после перестановки
}

// Проверяет, готово ли решение: заполнены ли все n позиций?
bool is_a_solution(int a[], int k, int n) {
    return (k == n);                   // true, если позиций заполнено столько же, сколько нужно
}

// Точка входа: запускает генерацию всех перестановок чисел {1, 2, ..., n}
void generate_permutations(int n) {
    int a[NMAX];                       // вектор решений (a[i] = какое число стоит на позиции i)
    backtrack(a, 0, n);                // старт: k = 0 — ни одна позиция не заполнена
}

// ---------- Каркас backtrack (тело) ----------

// Универсальный обходчик дерева решений (тот же, что для подмножеств)
void backtrack(int a[], int k, int n) {
    int c[NMAX];                       // массив кандидатов (для перестановок может быть до n штук)
    int nc;                            // сколько кандидатов реально положили в c[]

    if (is_a_solution(a, k, n)) {      // если решение готово (k == n)...
        process_solution(a, k, n);     // ...выводим перестановку и...
    } else {                           // ...иначе идём вглубь
        k++;                           // увеличиваем глубину (перешли к следующей позиции)
        construct_candidates(a, k, n, c, &nc);  // получаем кандидатов для позиции k
                                                // (передаём &nc, чтобы функция вернула значение)
        for (int i = 0; i < nc; i++) { // перебираем всех кандидатов
            a[k] = c[i];               // делаем выбор: ставим число c[i] на позицию k
            backtrack(a, k, n);        // уходим вглубь (рекурсия)
                                       // после возврата i++ → берём следующего кандидата
        }
    }
}

int main() {
    std::cout << "Перестановки {1..3}:\n";
    generate_permutations(50);         
    std::cout << "\nПерестановки {1..4}:\n";
    generate_permutations(4);          

    return 0;                         
}
