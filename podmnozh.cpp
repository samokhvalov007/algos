#include <iostream>

constexpr int NMAX = 100;              // максимальный размер множества (размер массива a[])

// ---------- Листинг 9.3: базовые процедуры ----------

// Проверяет, готово ли решение: прошли ли все n элементов?
bool is_a_solution(int a[], int k, int n) {
    return (k == n);                   // true, если решений принято столько же, сколько элементов
}

// Заполняет c[] вариантами, которые можно поставить на позицию k
void construct_candidates(int a[], int k, int n, int c[], int *nc) {
    c[0] = true;                       // вариант 1: включить элемент k в подмножество
    c[1] = false;                      // вариант 2: не включать элемент k
    *nc = 2;                           // в массиве c[] ровно 2 кандидата (пишем по указателю)
}

// Обрабатывает готовое решение — здесь просто печатает подмножество
void process_solution(int a[], int k, int n) {
    std::cout << " {";

    for (int i = 1; i <= k; i++) {
        if (a[i] == true) {            // если i-й элемент включён в подмножество
            std::cout << i;            // печатаем его номер
        }
    }

    std::cout << "}\n";
}

// ---------- Каркас backtrack (сама процедура) ----------

// Рекурсивный обходчик дерева решений
void backtrack(int a[], int k, int n) {
    int c[2];                          // массив кандидатов (для подмножеств всегда максимум 2)
    int nc;                            // сколько кандидатов реально положили в c[]

    if (is_a_solution(a, k, n)) {      // если решение готово (k == n)...
        process_solution(a, k, n);     // ...выводим его и...
    } else {                           // ...иначе идём вглубь
        k++;                           // увеличиваем глубину (перешли к следующему элементу)
        construct_candidates(a, k, n, c, &nc);  // получаем варианты для позиции k
                                                // (передаём &nc — адрес, чтобы функция вернула значение)
        for (int i = 0; i < nc; i++) {
            a[k] = c[i];               // делаем выбор: ставим кандидата на позицию k
            backtrack(a, k, n);        // уходим вглубь (рекурсия)
                                       // после возврата i++ → берём следующего кандидата
        }
    }
}

// ---------- Листинг 9.4: точка входа ----------

// Запускает генерацию всех подмножеств для множества {1, 2, ..., n}
void generate_subsets(int n) {
    int a[NMAX];                       // вектор решений (булев массив: true = включён)
    backtrack(a, 0, n);                // старт: k = 0 — ещё ничего не выбрано
}

int main() {
    std::cout << "Подмножества {1..3}:\n";
    generate_subsets(3);         

    std::cout << "\nПодмножества {1..4}:\n";
    generate_subsets(4);              

    return 0;                          
}
